def write_site(out, index, boards, models, summaries, bench, external=()):
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for f in ('style.css', 'app.js'):
        shutil.copy(SITE_SRC / f, out / f)
    (out / '.nojekyll').write_text('')
    (out / 'index.html').write_text(site_index(index, boards, models, summaries, bench, external), encoding='utf-8')
    for b, s in zip(boards, summaries):
        d = out / 'tasks' / b['task']['id'] / b['lang']
        d.mkdir(parents=True)
        (d / 'index.html').write_text(site_task(b, models, s), encoding='utf-8')
    (out / 'buddhistbench').mkdir()
    (out / 'buddhistbench' / 'index.html').write_text(site_bench(bench), encoding='utf-8')
    allrows = [{k: v for k, v in r.items() if not k.startswith('_')} for b in boards for r in b['rows']]
    (out / 'results.json').write_text(json.dumps({'skills': allrows, 'buddhistbench': bench['rows'] if bench else []},
                                                 ensure_ascii=False, indent=1), encoding='utf-8')


