#!/usr/bin/env python3
"""Build every leaderboard from the result.json files.

python3 scripts/build_leaderboards.py                 # rewrite LEADERBOARD.md files and the README table
python3 scripts/build_leaderboards.py --check         # fail if they are out of date (used by check.py)
python3 scripts/build_leaderboards.py --site _site [--bench ../buddhist-bench]
                                                      # also write the static site (GitHub Pages)

Inputs (see docs/results.md):
  tasks/<task>/results/<lang>/runs/<run>/result.json   one per skill, model and data version
  tasks/<task>/results/<lang>/skills.json              approach, status and links per skill
  models.json                                          model names and price tiers
  <bench>/tracks/<track>/results/<lang>/runs/<run>/{run.json,scores.json}   BuddhistBench model runs
"""
import argparse, html, json, re, shutil, sys, urllib.parse, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE_SRC = ROOT / 'site'
REPO = 'https://github.com/BuddhistAI/buddhist-benchmarks'
BENCH_REPO = 'https://github.com/BuddhistAI/buddhist-bench'
README_START, README_END = '<!-- leaderboards:start -->', '<!-- leaderboards:end -->'
GENERATED = '<!-- Generated by scripts/build_leaderboards.py from runs/*/result.json and skills.json. Do not edit by hand. -->'
STRONG_MARGIN = 0.02  # "strong" = within this much of the best headline score on that data version
SPLIT_NAMES = {'all': 'All', 'same-book': 'Same book', 'held-out-book': 'Held-out book'}
REQUIRED = ['schema', 'task', 'language', 'data_version', 'scorer_version', 'skill', 'variant', 'skill_version',
            'skill_ref', 'model', 'repeats', 'headline', 'scores', 'cost_usd', 'date', 'by']


def load_json(p):
    return json.loads(Path(p).read_text(encoding='utf-8'))


def semver_key(v):
    return tuple(int(x) for x in v.split('.'))


def split_name(s):
    return SPLIT_NAMES.get(s, s.replace('-', ' ').capitalize())


# ---------------------------------------------------------------- loading

def load_results(errors):
    index = load_json(ROOT / 'tasks' / 'index.json')
    models = load_json(ROOT / 'models.json')['models']
    boards = []
    for task in index['tasks']:
        for res_dir in sorted((ROOT / 'tasks' / task['id'] / 'results').glob('*')):
            if not res_dir.is_dir():
                continue
            lang = res_dir.name
            skills_file = res_dir / 'skills.json'
            meta = load_json(skills_file) if skills_file.exists() else {'skills': {}}
            rows = []
            for f in sorted(res_dir.glob('runs/*/result.json')):
                r = load_json(f)
                rel = f.relative_to(ROOT).as_posix()
                missing = [k for k in REQUIRED if k not in r]
                if missing:
                    errors.append(f'{rel}: missing {", ".join(missing)}')
                    continue
                if r['task'] != task['id'] or r['language'] != lang:
                    errors.append(f'{rel}: task/language do not match its folder')
                if r['model'] not in models:
                    errors.append(f'{rel}: model {r["model"]!r} is not in models.json')
                if 'all' not in r['scores'] or r['headline'] not in r['scores']['all']:
                    errors.append(f'{rel}: scores.all.{r["headline"]} is required')
                    continue
                if r['variant'] not in meta['skills']:
                    errors.append(f'{rel}: variant {r["variant"]!r} is not in {skills_file.relative_to(ROOT).as_posix()}')
                if meta['skills'].get(r['variant'], {}).get('hidden'):
                    continue
                r['_run'] = f.parent.relative_to(res_dir).as_posix()
                r['_path'] = f.parent.relative_to(ROOT).as_posix()
                rows.append(r)
            if rows:
                boards.append({'task': task, 'lang': lang, 'meta': meta, 'rows': rows})
    return index, models, boards


def load_external(errors, fetch):
    """Leaderboards other organizations run (external.json). With fetch, read their live top rows."""
    entries = load_json(ROOT / 'external.json')['leaderboards']
    for x in entries:
        x['rows'] = []
        if not fetch or x.get('parser') != 'bdrc-ocr':
            continue
        try:
            req = urllib.request.Request(x['data_url'], headers={'User-Agent': 'buddhistai-leaderboards'})
            with urllib.request.urlopen(req, timeout=30) as r:
                text = r.read().decode('utf-8')
            i = text.index('const DATA =') + len('const DATA =')
            data, _ = json.JSONDecoder().raw_decode(text[i:].lstrip())
            models = sorted(data['models'], key=lambda m: m['overall']['mean'])
            x['updated'] = data.get('generated')
            x['n_items'] = data.get('n_images')
            x['rows'] = [dict(name=m.get('model_display') or m.get('model'), by=m.get('engine_display') or m.get('engine'),
                              kind=m.get('cls', ''), score=m['overall']['mean'], coverage=m.get('coverage'))
                         for m in models[:x.get('top', 5)]]
        except Exception as ex:  # their page changed or is unreachable: show the card as a link only
            errors.append(f"{x['id']}: could not read {x['data_url']} ({ex})")
    return entries


def load_bench(path, errors):
    """BuddhistBench model runs (format: buddhist-bench docs/results.md)."""
    if not path:
        return None
    path = Path(path)
    out = {'available': path.exists(), 'rows': [], 'version': None}
    if not path.exists():
        return out
    if (path / 'VERSION').exists():
        out['version'] = (path / 'VERSION').read_text().strip()
    for runf in sorted(path.glob('tracks/*/results/*/runs/*/run.json')):
        scoref = runf.parent / 'scores.json'
        try:
            run, scores = load_json(runf), load_json(scoref)
        except Exception as e:  # a half-written run should not break the site
            errors.append(f'buddhist-bench {runf.parent.name}: {e}')
            continue
        if run.get('dry_run') or run.get('split') == 'example':
            continue
        overall = scores.get('overall', {})
        out['rows'].append({
            'track': run.get('track'), 'language': run.get('language'), 'mode': run.get('mode'),
            'variant': run.get('variant'), 'model': run.get('model'), 'release': run.get('release'),
            'track_version': run.get('track_version'), 'date': run.get('date'), 'cost_usd': run.get('cost_usd'),
            'score': overall.get('score'), 'incorrect': overall.get('incorrect'),
            'not_attempted': overall.get('not_attempted'),
            'search_rate': (scores.get('search') or {}).get('search_rate'),
            'by_tradition': scores.get('by_tradition'),
            'run': f'{BENCH_REPO}/tree/main/{runf.parent.relative_to(path).as_posix()}',
        })
    return out


# ---------------------------------------------------------------- summaries

def headline(r):
    return r['scores']['all'][r['headline']]['mean']


def summarize(board, models):
    """Per data version: champion, top row, cheapest strong model."""
    meta, rows = board['meta'], board['rows']
    versions = sorted({r['data_version'] for r in rows}, key=semver_key, reverse=True)
    latest = [r for r in rows if r['data_version'] == versions[0]]
    best = max(latest, key=headline)
    promoted = meta.get('promoted', {})
    champ_rows = [r for r in latest if r['variant'] == promoted.get('variant')]
    champ_best = max(champ_rows, key=headline) if champ_rows else None
    strong = [r for r in latest if headline(r) >= headline(best) - STRONG_MARGIN]
    cheapest = min(strong, key=lambda r: (models[r['model']]['tier'], -headline(r)))
    return {
        'versions': versions, 'data_version': versions[0], 'best': best, 'champion': champ_best,
        'cheapest': cheapest, 'skills': len({r['variant'] for r in latest} - {meta.get('baseline')}),
        'models': sorted({r['model'] for r in latest}, key=lambda m: models[m]['tier']),
        'last_tested': max(r['date'] for r in latest), 'headline': best['headline'],
        'benchmarks': {v: benchmark_info(board['task']['id'], board['lang'], v, rows) for v in versions},
    }


def benchmark_info(task_id, lang, version, rows):
    """What a data version is: name, tag, folder, items, scorer. Read from the data set's README and items.json."""
    major = version.split('.')[0]
    rel = f'tasks/{task_id}/data/{lang}/v{major}'
    d = ROOT / rel
    tag = f'{task_id}/{lang}@{version}'
    info = {'name': f'{task_id}/{lang} {version}', 'version': version, 'tag': tag, 'folder': rel + '/',
            'url': f'{REPO}/tree/{urllib.parse.quote(tag, safe="/")}/{rel}',
            'scorer_version': sorted({r['scorer_version'] for r in rows if r['data_version'] == version}),
            'items': None, 'purpose': None, 'subsets': {}}
    readme = d / 'README.md'
    if readme.exists():
        text = readme.read_text(encoding='utf-8')
        m = re.search(r'\*\*Purpose:\*\*\s*(.+)', text)
        if m:
            purpose = re.sub(r'\s*\([^)]*\)', '', m.group(1)).strip()
            info['purpose'] = purpose[:1].upper() + purpose[1:]
        m = re.search(r'\*\*Version:\*\*\s*([0-9.]+)', text)
        if m and m.group(1) != version:
            info['note'] = f'the data folder is now at {m.group(1)}; these rows were scored on {version}'
    items_file = d / 'items.json'
    if items_file.exists():
        items = json.loads(items_file.read_text(encoding='utf-8'))
        info['items'] = len(items)
        for it in items:
            if it.get('subset'):
                info['subsets'][it['subset']] = info['subsets'].get(it['subset'], 0) + 1
    elif (d / 'inputs').exists():
        info['items'] = sum(1 for _ in (d / 'inputs').glob('*'))
    return info


def bench_line(b):
    parts = [f"{b['items']} items" if b['items'] else None,
             ', '.join(f"{n} {s.replace('-', ' ')}" for s, n in b['subsets'].items()) or None,
             'scorer ' + ', '.join(b['scorer_version'])]
    return '; '.join(p for p in parts if p)


def fmt(m):
    if m is None:
        return '–'
    return f"{m['mean']:.3f} ± {m['std']:.3f}" if len(m.get('runs', [])) > 1 else f"{m['mean']:.3f}"


def fmt_cost(c):
    return 'not recorded' if c is None else f'${c:,.2f}'


def display(meta, variant):
    return meta['skills'].get(variant, {}).get('name') or variant


def skill_label(r, meta=None):
    name = display(meta, r['variant']) if meta else r['variant']
    link = (meta or {}).get('skills', {}).get(r['variant'], {}).get('skill_md')
    label = f"[{name}]({link})" if link else name
    return f"{label} {r['skill_version']}" + (f" (`{r['variant']}`)" if name != r['variant'] else '')


