def e(s):
    return html.escape(str(s))


def rank_views(board, models, summary):
    """Ranked skill lists for the overview cards: the mean over models, then each model."""
    meta = board['meta']
    rows = [r for r in board['rows'] if r['data_version'] == summary['data_version']]
    ms = summary['models']
    by_variant = {}
    for r in rows:
        by_variant.setdefault(r['variant'], {})[r['model']] = r
    views = []
    if len(ms) > 1:
        views.append(('Mean', [(v, d, sum(headline(d[m]) for m in ms if m in d) / len([m for m in ms if m in d]))
                               for v, d in by_variant.items()]))
    for m in ms:
        views.append((models[m]['name'].replace('Claude ', ''), [(v, d, headline(d[m])) for v, d in by_variant.items() if m in d]))
    out = []
    base_v = meta.get('baseline')
    for label, items in views:
        items.sort(key=lambda x: (x[0] == base_v, -x[2]))
        base = next((sc for v, d, sc in items if v == base_v), None)
        out.append((label, [dict(variant=v, base=v == base_v, gain=None if base is None or v == base_v else sc - base, version=next(iter(d.values()))['skill_version'],
                                 status=meta['skills'].get(v, {}).get('status', ''), name=display(meta, v), score=sc,
                                 link=meta['skills'].get(v, {}).get('skill_md') or meta['skills'].get(v, {}).get('source')) for v, d, sc in items]))
    return out


def rank_list(items, hidden):
    scores = [i['score'] for i in items]
    lo, hi = min(scores) - 0.05, max(scores)
    lis = []
    n = 0
    for i in items:
        st = i['status']
        ranked = st != 'reference' and not i['base']
        n += ranked
        w = 100 if hi == lo else 12 + 88 * (i['score'] - lo) / (hi - lo)
        badge = '' if i['base'] else f'<span class="badge {e(st)}">{"best skill" if st == "promoted" else e(st)}</span>' if st else ''
        cls = 'base' if i['base'] else 'ref' if st == 'reference' else f'r{n}' if n <= 3 else ''
        gain = (f'<span class="gain">before</span>' if i['base'] else
                f'<span class="gain {"up" if i["gain"] >= 0 else "down"}">{i["gain"]:+.3f}</span>' if i['gain'] is not None else '')
        lis.append(f'''<li class="{cls}">
<span class="pos">{n if ranked else '–'}</span>
<span class="who">{f'<a class="name" href="{e(i["link"])}" title="Open the skill as tested">{e(i["name"])}</a>' if i.get("link") else f'<span class="name">{e(i["name"])}</span>'}{badge}<span class="bar"><i style="width:{w:.0f}%"></i></span></span>
<span class="val">{i["score"]:.3f}{gain}</span>
</li>''')
    return f'<ol class="rank"{" hidden" if hidden else ""}>{"".join(lis)}</ol>'


def external_card(x):
    rows = x['rows']
    if rows:
        lo, hi = min(r['score'] for r in rows), max(r['score'] for r in rows) + 0.02
        lis = ''.join(f'''<li class="{f'r{n}' if n <= 3 else ''}">
<span class="pos">{n}</span>
<span class="who"><span class="name">{e(r["name"])}</span><span class="badge">{e(r["by"])}</span><span class="bar"><i style="width:{12 + 88 * (hi - r["score"]) / (hi - lo):.0f}%"></i></span></span>
<span class="val">{r["score"] * 100:.1f}%</span>
</li>''' for n, r in enumerate(rows, 1))
        body = f'<p class="sub tabs-note">{e(x["metric"])}, lower is better</p><ol class="rank">{lis}</ol>'
    else:
        body = f'<div class="soon-body">{e(x["metric"])} · open the leaderboard</div>'
    meta = ' · '.join(p for p in [f'by {x["maintainer"]}', f'updated {x["updated"]}' if x.get('updated') else '',
                                  f'{x["n_items"]} pages' if x.get('n_items') else ''] if p)
    return f'''<article class="lb-card ext">
<header><p class="kicker">{e(x["kicker"])} · external</p><h2><a href="{e(x["url"])}">{e(x["title"])}</a></h2>
<p class="sub">{e(x["summary"])}</p></header>
{body}
<footer><span class="sub">{e(meta)}</span><a class="more" href="{e(x["url"])}">Open on {e(x["host"])} →</a></footer>
</article>'''


