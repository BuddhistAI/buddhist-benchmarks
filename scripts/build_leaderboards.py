def leaderboard_md(board, models, summary):
    t, lang, meta, rows = board['task'], board['lang'], board['meta'], board['rows']
    hl = summary['headline']
    splits = [s for s in rows[0]['scores'] if s != 'all']
    other = [k for k in rows[0]['scores']['all'] if k != hl]
    lines = [GENERATED, '', f"# {t['id']}: {lang} leaderboard", '',
             f"Headline metric: `{hl}` (see [TASK.md](../../TASK.md)). Higher is better. Rows are only ranked against rows "
             "on the same data version and model ([VERSIONING.md](../../../../VERSIONING.md)). Values are the mean ± "
             "standard deviation over the run's repeats. Live site: https://buddhistai.github.io/buddhist-benchmarks/", '']
    p = meta.get('promoted')
    if p:
        lines += [f"Best skill (installed from buddhist-skills): [`{t['id']}` skill]({p['skill']}) {p['version']} "
                  f"(variant {p['variant']}), promoted {p['date']}." +
                  (f" Full report: [REPORT.md]({meta['report']})." if meta.get('report') else ''), '']
    for n in meta.get('notes', []):
        lines += [f'- {n}']
    if meta.get('notes'):
        lines.append('')
    for v in summary['versions']:
        bi = summary['benchmarks'][v]
        lines += [f"## Benchmark {bi['name']}", '',
                  f"Data set [`{bi['folder']}`]({bi['url']}) at tag `{bi['tag']}`: {bench_line(bi)}." +
                  (f" {bi['purpose']}" if bi['purpose'] else '') + (f" Note: {bi['note']}." if bi.get('note') else ''), '']
        vrows = [r for r in rows if r['data_version'] == v]
        for m in sorted({r['model'] for r in vrows}, key=lambda m: models[m]['tier']):
            mrows = sorted([r for r in vrows if r['model'] == m], key=headline, reverse=True)
            lines += [f'### {models[m]["name"]} (`{m}`)', '']
            base = next((r for r in mrows if r['variant'] == meta.get('baseline')), None)
            mrows = [r for r in mrows if r is not base] + ([base] if base else [])
            gain = lambda r: ('before' if r is base else f"{headline(r) - headline(base):+.3f}") if base else '–'
            head = (['Rank', 'Skill', 'Status', f'{hl}', 'Gain vs. no skill'] + [f'{hl}, {split_name(s).lower()}' for s in splits] +
                    other + ['Cost', 'Date', 'Skill ref', 'Run'])
            lines += ['| ' + ' | '.join(head) + ' |', '|' + ' --- |' * len(head)]
            n = 0
            for r in mrows:
                st = meta['skills'].get(r['variant'], {}).get('status', '')
                ranked = r is not base and st != 'reference'
                n += ranked
                cells = ([str(n) if ranked else '–', skill_label(r, meta), st, fmt(r['scores']['all'][hl]), gain(r)] +
                         [fmt(r['scores'].get(s, {}).get(hl)) for s in splits] +
                         [fmt(r['scores']['all'].get(k)) for k in other] +
                         [fmt_cost(r['cost_usd']), r['date'], f"`{r['skill_ref']}`", f"[run](./{r['_run']}/)"])
                lines.append('| ' + ' | '.join(cells) + ' |')
            lines.append('')
        if meta.get('splits'):
            lines += ['Splits:', '']
            lines += [f'- **{split_name(s)}:** {d}' for s, d in meta['splits'].items()]
            lines.append('')
    return '\n'.join(lines)


def readme_table(boards, models, summaries):
    lines = [README_START, '', '| Task | Benchmark | Best skill | Score |', '| --- | --- | --- | --- |']
    for b, s in zip(boards, summaries):
        c, bi = s['champion'], s['benchmarks'][s['data_version']]
        champ = (f"[{display(b['meta'], c['variant'])}]({b['meta']['promoted']['skill']}) {c['skill_version']}" if b['meta'].get('promoted', {}).get('skill')
                 else f"{display(b['meta'], c['variant'])} {c['skill_version']}") if c else '–'
        score = f"{headline(c):.3f} ({models[c['model']]['name']})" if c else '–'
        lines.append(f"| [{b['task']['title']}, {lang_name(b['lang'])}](./tasks/{b['task']['id']}/results/{b['lang']}/LEADERBOARD.md) | "
                     f"[{bi['name']}]({bi['url']}) | {champ} | {score} |")
    lines += ['', "Best skill: the top shippable skill, the one people install. Score: its best result on the task's headline metric. Each leaderboard compares every skill and model. "
              'Generated by `scripts/build_leaderboards.py`; site: https://buddhistai.github.io/buddhist-benchmarks/', '', README_END]
    return '\n'.join(lines)

