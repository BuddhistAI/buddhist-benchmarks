def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if generated Markdown is out of date')
    ap.add_argument('--site', help='write the static site to this folder')
    ap.add_argument('--bench', help='path to a buddhist-bench checkout, for the BuddhistBench page')
    a = ap.parse_args()

    errors = []
    index, models, boards = load_results(errors)
    if errors:
        print('\n'.join(errors))
        sys.exit(1)
    summaries = [summarize(b, models) for b in boards]

    targets = {ROOT / 'tasks' / b['task']['id'] / 'results' / b['lang'] / 'LEADERBOARD.md': leaderboard_md(b, models, s) + '\n'
               for b, s in zip(boards, summaries)}
    readme = (ROOT / 'README.md').read_text(encoding='utf-8')
    if README_START in readme and README_END in readme:
        pre, rest = readme.split(README_START, 1)
        post = rest.split(README_END, 1)[1]
        targets[ROOT / 'README.md'] = pre + readme_table(boards, models, summaries) + post
    else:
        errors.append(f'README.md: missing {README_START} ... {README_END} markers')

    stale = [p for p, text in targets.items() if not p.exists() or p.read_text(encoding='utf-8') != text]
    if a.check:
        errors += [f'{p.relative_to(ROOT).as_posix()}: out of date, run python3 scripts/build_leaderboards.py' for p in stale]
    else:
        for p in stale:
            p.write_text(targets[p], encoding='utf-8', newline='\n')
            print('wrote', p.relative_to(ROOT).as_posix())
    if errors:
        print('\n'.join(errors))
        sys.exit(1)
    if a.site:
        bench_errors = []
        bench = load_bench(a.bench, bench_errors)
        for w in bench_errors:
            print('warning:', w)
        write_site(a.site, index, boards, models, summaries, bench)
        print('site written to', a.site)


if __name__ == '__main__':
    main()
