#!/usr/bin/env python3
"""Build STATE.md: the state of AI for Buddhist texts, with what is measured and what is missing.

python3 scripts/build_state.py [--bench ../buddhist-bench]    # rewrite STATE.md
python3 scripts/build_state.py --check [--bench ...]          # fail if it is out of date

Everything in STATE.md comes from files in this repo (tasks/index.json, result.json files,
external.json) and, with --bench, from a buddhist-bench checkout (tracks/index.json, data, runs).
Write the hand-written parts in the template below, never in STATE.md.
"""
import argparse, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_leaderboards as bl  # noqa: E402

ROOT = bl.ROOT
SITE = 'https://buddhistai.github.io/buddhist-benchmarks/'
BENCH_REPO = bl.BENCH_REPO
# Source languages every task should eventually cover, shown as columns even before they have data.
CORE_LANGS = ['bo', 'sa', 'pi', 'lzh']
NAMES = {'bo': 'Tibetan', 'sa': 'Sanskrit', 'pi': 'Pali', 'lzh': 'Classical Chinese', 'zh': 'Chinese',
         'ja': 'Japanese', 'ko': 'Korean', 'mn': 'Mongolian', 'dz': 'Dzongkha', 'en': 'English', 'th': 'Thai',
         'si': 'Sinhala', 'my': 'Burmese', 'vi': 'Vietnamese', 'it': 'Italian', 'fr': 'French', 'de': 'German',
         'es': 'Spanish'}


def name(code):
    return NAMES.get(code, code)


def task_cells(index, boards, models):
    """{task_id: {lang: summary}} for every task with results, and the data-only languages."""
    cells = {t['id']: {} for t in index['tasks']}
    for b in boards:
        cells[b['task']['id']][b['lang']] = bl.summarize(b, models)
    data_only = {}
    for t in index['tasks']:
        for d in sorted((ROOT / 'tasks' / t['id'] / 'data').glob('*')):
            if d.is_dir() and d.name not in cells[t['id']]:
                data_only.setdefault(t['id'], []).append(d.name)
    return cells, data_only


def bench_state(path):
    if not path or not Path(path).exists():
        return None
    path = Path(path)
    tracks = bl.load_json(path / 'tracks' / 'index.json')['tracks']
    out = []
    for t in tracks:
        items, langs = 0, set()
        for f in (path / 'tracks' / t['id'] / 'data').glob('*/*.jsonl'):
            if f.name == 'example.jsonl':
                continue
            n = sum(1 for line in f.read_text(encoding='utf-8').splitlines() if line.strip())
            if n:
                items += n
                langs.add(f.parent.name)
        runs = len(list((path / 'tracks' / t['id'] / 'results').glob('*/runs/*/run.json')))
        out.append({**t, 'items': items, 'langs': sorted(langs), 'runs': runs})
    version = (path / 'VERSION').read_text().strip() if (path / 'VERSION').exists() else None
    return {'version': version, 'tracks': out}


def build(bench_path):
    errors = []
    index, models, boards = bl.load_results(errors)
    if errors:
        raise SystemExit('\n'.join(errors))
    cells, data_only = task_cells(index, boards, models)
    langs = list(CORE_LANGS)
    for t in cells.values():
        langs += [l for l in t if l not in langs]
    for ls in data_only.values():
        langs += [l for l in ls if l not in langs]
    external = bl.load_json(ROOT / 'external.json')['leaderboards']
    bench = bench_state(bench_path)

    measured = [(tid, l) for tid, t in cells.items() for l in t]
    active = [t for t in index['tasks'] if cells[t['id']] or t['id'] in data_only]
    L = []
    w = L.append
    w('<!-- Generated by scripts/build_state.py. Do not edit by hand. -->')
    w('# State of AI for Buddhist texts')
    w('')
    w('What AI can do today with Buddhist texts, measured on open benchmarks, and where nothing is measured yet. '
      'It is built from the benchmarks and results in this repo and in '
      f'[BuddhistBench]({BENCH_REPO}), and rebuilt whenever they change. For the full rankings and costs, see the '
      f'[leaderboard]({SITE}).')
    w('')
    w('## At a glance')
    w('')
    w(f'- **Text tasks:** {len(index["tasks"])} defined, {len(active)} with a benchmark, '
      f'{len(measured)} task and language pair{"s" if len(measured) != 1 else ""} with results.')
    if bench:
        real = [t for t in bench['tracks'] if t['items']]
        tested = [t for t in bench['tracks'] if t['runs']]
        w(f'- **Buddhist knowledge (BuddhistBench {bench["version"]}):** {len(bench["tracks"])} tracks planned or open, '
          f'{len(real)} with real questions, {len(tested)} with model results.')
    w(f'- **Other open leaderboards we follow:** {len(external)}.')
    w('')
    w('## Text tasks by language')
    w('')
    w('Best score on each task\'s headline metric (0 to 1, higher is better); the skill and model behind it are listed below. '
      'A dash means there is no benchmark yet.')
    w('')
    w('| Task | ' + ' | '.join(name(l) for l in langs) + ' |')
    w('| --- | ' + ' | '.join('---' for _ in langs) + ' |')
    for t in index['tasks']:
        row = []
        for l in langs:
            s = cells[t['id']].get(l)
            if s:
                p = s['picks'].get('overall') or s['best']
                link = f'tasks/{t["id"]}/results/{l}/LEADERBOARD.md'
                row.append(f'[**{bl.headline(p):.2f}**]({link})')
            elif l in data_only.get(t['id'], []):
                row.append('data, no results')
            else:
                row.append('–')
        w(f'| {t["title"]} | ' + ' | '.join(row) + ' |')
    w('')
    if measured:
        w('Details:')
        w('')
        for tid, t in cells.items():
            title = next(x['title'] for x in index['tasks'] if x['id'] == tid)
            for l, s in t.items():
                p = s['picks'].get('overall') or s['best']
                v = s['picks'].get('value')
                line = (f'- **{title}, {name(l)}:** {bl.headline(p):.3f} {p["headline"]} by '
                        f'{bl.display(boards_meta(boards, tid, l), p["variant"])} on {models[p["model"]]["name"]}')
                if v and v is not p:
                    line += f'; best value {bl.headline(v):.3f} on {models[v["model"]]["name"]}'
                line += f' (benchmark {tid}/{l} {s["data_version"]}, last tested {s["last_tested"]}).'
                w(line)
        w('')

    if bench:
        w('## Buddhist knowledge (BuddhistBench)')
        w('')
        w('How well AI models know the Buddhist traditions, asked per tradition and per language.')
        w('')
        w('| Track | Kind | Questions | Languages | Model results |')
        w('| --- | --- | ---: | --- | ---: |')
        for t in bench['tracks']:
            kind = t.get('kind', 'tradition')
            q = f"{t['items']:,}" if t['items'] else ('–' if t['status'] == 'planned' else 'examples only')
            w(f'| [{t["title"]}]({BENCH_REPO}/tree/main/tracks/{t["id"]}) | {kind} | {q} | '
              f'{", ".join(name(l) for l in t["langs"]) or "–"} | {t["runs"] or "–"} |')
        w('')

    if external:
        w('## Other open leaderboards')
        w('')
        for x in external:
            w(f'- [{x["title"]}]({x["url"]}) ({x["maintainer"]}): {x["summary"]}')
        w('')

    w('## Gaps')
    w('')
    planned = [t for t in index['tasks'] if t not in active]
    if planned:
        w(f'- **Text tasks with no benchmark yet ({len(planned)}):** ' + ', '.join(t['title'].lower() for t in planned) + '.')
    for l in CORE_LANGS:
        n = sum(1 for t in cells.values() if l in t)
        if n == 0:
            w(f'- **{name(l)}:** no text task is measured yet.')
    if bench:
        empty = [t['title'] for t in bench['tracks'] if t['status'] != 'planned' and not t['items'] and 'example' not in t['id']]
        planned_tracks = [t['title'] for t in bench['tracks'] if t['status'] == 'planned']
        no_runs = [t['title'] for t in bench['tracks'] if t['items'] and not t['runs']]
        if empty:
            w(f'- **BuddhistBench tracks with no real questions yet:** {", ".join(empty)}.')
        if planned_tracks:
            w(f'- **Traditions whose BuddhistBench track is only planned:** {", ".join(planned_tracks)}.')
        if no_runs:
            w(f'- **BuddhistBench tracks with questions but no model results yet:** {", ".join(no_runs)}.')
    w('')
    w('## Close a gap')
    w('')
    w('- Add test data for a task and language: [CONTRIBUTING.md](CONTRIBUTING.md).')
    w('- Score your tool or model on an existing benchmark: [SUBMIT.md](SUBMIT.md).')
    w(f'- Bring exam papers or expert questions for your tradition: [BuddhistBench]({BENCH_REPO}/blob/main/CONTRIBUTING.md).')
    w('- Propose a new task or ask a question: [Discussions](https://github.com/orgs/BuddhistAI/discussions).')
    return '\n'.join(L) + '\n'


def boards_meta(boards, tid, lang):
    return next(b['meta'] for b in boards if b['task']['id'] == tid and b['lang'] == lang)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--bench', help='path to a buddhist-bench checkout')
    a = ap.parse_args()
    text = build(a.bench)
    p = ROOT / 'STATE.md'
    if a.check:
        if not p.exists() or p.read_text(encoding='utf-8') != text:
            raise SystemExit('STATE.md: out of date, run python3 scripts/build_state.py --bench <buddhist-bench>')
    elif not p.exists() or p.read_text(encoding='utf-8') != text:
        p.write_text(text, encoding='utf-8', newline='\n')
        print('wrote STATE.md')


if __name__ == '__main__':
    main()
